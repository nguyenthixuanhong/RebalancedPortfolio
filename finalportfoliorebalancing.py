def compute_next(Vt, p_list, S1c_series, S2c_series, S3c_series, t):
  n1t = np.floor(p_list[0]*Vt / (10*S1c_series[t]))
  n2t = np.floor(p_list[1]*Vt / (10*S2c_series[t]))
  n3t = np.floor(p_list[2]*Vt / (10*S3c_series[t]))

  # print('t:', t, 'n1t:', n1t, 'n2t:', n2t, 'n3t:', n3t)
  # print(S1c_series[t+1], S2c_series[t+1], S3c_series[t+1])

  A1_next_tmp = 10*n1t*S1c_series[t+1]
  A2_next_tmp = 10*n2t*S2c_series[t+1]
  A3_next_tmp = 10*n3t*S3c_series[t+1]
  A4_next_tmp = Vt - 10*n1t*S1c_series[t] - 10*n2t*S2c_series[t] - 10*n3t*S3c_series[t]
  V_next = A1_next_tmp + A2_next_tmp + A3_next_tmp + A4_next_tmp
  A1_next = p_list[0]*V_next
  A2_next = p_list[1]*V_next
  A3_next = p_list[2]*V_next
  A4_next = p_list[3]*V_next

  # print('A1_next:', A1_next, 'A2_next:', A2_next, 'A3_next:', A3_next, 'V_next:', V_next)

  return V_next, A1_next, A2_next, A3_next, A4_next


